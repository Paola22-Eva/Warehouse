/**
 * Перечисление статусов документа на складе.
 * Определяет жизненный цикл накладной: от черновика до завершения или отмены.
 */
public enum DocumentStatus {
    /** Документ создан, но ещё не подтверждён */
    DRAFT,
    /** Документ проверен и утверждён кладовщиком */
    CONFIRMED,
    /** Операция по документу полностью выполнена */
    COMPLETED,
    /** Документ аннулирован, операция отменена */
    CANCELLED
}
